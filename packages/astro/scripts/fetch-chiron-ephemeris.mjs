/**
 * One-shot generator: pull geocentric apparent Chiron longitudes from JPL
 * Horizons and write packages/astro/src/chiron-ephemeris-data.ts.
 *
 * Re-run only when regenerating the table. The committed file is the source
 * of truth at runtime (no network).
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const JD0 = 2415020.5; // 1900-01-01 00:00 UT
const JD_END = 2488448.5; // 2101-01-15 00:00 UT (room for retrograde at 2100-12-31)
const STEP = 10;
const CHUNK_STEPS = 180; // 1800 days per request

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

function horizonsUrl(startJd, stopJd) {
  const q = new URLSearchParams({
    format: "text",
    COMMAND: "'2060'",
    OBJ_DATA: "'NO'",
    MAKE_EPHEM: "'YES'",
    EPHEM_TYPE: "'OBSERVER'",
    CENTER: "'500@399'",
    START_TIME: `'JD ${startJd}'`,
    STOP_TIME: `'JD ${stopJd}'`,
    STEP_SIZE: `'${STEP} d'`,
    QUANTITIES: "'31'",
    ANG_FORMAT: "'DEG'",
    CSV_FORMAT: "'YES'",
    CAL_FORMAT: "'JD'",
  });
  return `https://ssd.jpl.nasa.gov/api/horizons.api?${q.toString()}`;
}

function parseHorizons(text) {
  const start = text.indexOf("$$SOE");
  const end = text.indexOf("$$EOE");
  if (start < 0 || end < 0) {
    throw new Error(`Horizons response missing $$SOE/$$EOE:\n${text.slice(0, 400)}`);
  }
  const rows = [];
  for (const line of text.slice(start + 5, end).split("\n")) {
    const trimmed = line.trim();
    if (!trimmed) continue;
    const parts = trimmed.split(",").map((p) => p.trim());
    // CAL_FORMAT=JD → first col is JD, ObsEcLon is the longitude column.
    const jd = Number(parts[0]);
    const lon = Number(parts[parts.length - 2] || parts[3]);
    if (!Number.isFinite(jd) || !Number.isFinite(lon)) {
      throw new Error(`Unparseable Horizons row: ${trimmed}`);
    }
    rows.push({ jd, lon });
  }
  return rows;
}

async function fetchChunk(startJd, stopJd, attempt = 1) {
  const url = horizonsUrl(startJd, stopJd);
  const res = await fetch(url);
  if (!res.ok) {
    if (attempt < 5) {
      await sleep(1000 * 2 ** attempt);
      return fetchChunk(startJd, stopJd, attempt + 1);
    }
    throw new Error(`Horizons HTTP ${res.status} for JD ${startJd}–${stopJd}`);
  }
  const text = await res.text();
  try {
    return parseHorizons(text);
  } catch (err) {
    if (attempt < 5) {
      await sleep(1000 * 2 ** attempt);
      return fetchChunk(startJd, stopJd, attempt + 1);
    }
    throw err;
  }
}

const samples = [];
for (let start = JD0; start <= JD_END; start += CHUNK_STEPS * STEP) {
  const stop = Math.min(start + CHUNK_STEPS * STEP, JD_END);
  process.stderr.write(`Fetching JD ${start} → ${stop}\n`);
  const rows = await fetchChunk(start, stop);
  for (const row of rows) {
    if (samples.length === 0 || row.jd > samples[samples.length - 1].jd + 1e-6) {
      samples.push(row);
    }
  }
  await sleep(250);
}

if (samples.length < 7000) {
  throw new Error(`Too few samples: ${samples.length}`);
}

const lons = samples.map((s) => Number(s.lon.toFixed(4)));
const out = `/**
 * AUTO-GENERATED. Do not edit by hand.
 * Regenerated by packages/astro/scripts/fetch-chiron-ephemeris.mjs
 *
 * Geocentric apparent ecliptic longitude of 2060 Chiron, tropical
 * (IAU76/80 ecliptic of date). Source: JPL Horizons API
 * https://ssd.jpl.nasa.gov/api/horizons.api
 * COMMAND=2060, CENTER=500@399 (Earth geocenter), QUANTITIES=31
 * (ObsEcLon, observer-centered ecliptic-of-date). Sampled every ${STEP}
 * days from JD ${JD0} (1900-01-01 00:00 UT) through JD ${samples[samples.length - 1].jd}.
 *
 * Not Swiss Ephemeris. A public-domain / public-API data table is not AGPL.
 */
export const CHIRON_JD0 = ${JD0};
export const CHIRON_STEP_DAYS = ${STEP};
export const CHIRON_LON_DEG: readonly number[] = [
${lons.map((n) => `  ${n},`).join("\n")}
];
`;

const dest = join(dirname(fileURLToPath(import.meta.url)), "../src/chiron-ephemeris-data.ts");
writeFileSync(dest, out);
process.stderr.write(`Wrote ${samples.length} samples to ${dest}\n`);
process.stderr.write(`First ${samples[0].jd} ${lons[0]}\nLast ${samples[samples.length - 1].jd} ${lons[lons.length - 1]}\n`);
